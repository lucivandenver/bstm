import multer from 'multer';
import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import { asyncRoute, requireUser, requireStudent } from '../middleware/security.js';
import * as student from '../controllers/studentController.js';
import { googleStart } from '../controllers/googleController.js';
const router = Router();
router.use(requireUser, requireStudent);
router.get('/', asyncRoute(student.dashboard));
router.get('/profile', asyncRoute(student.profilePage));
router.post('/profile/correction', asyncRoute(student.correction));
router.post('/profile/files', multer({ storage: multer.memoryStorage(), limits: { fileSize: 2 * 1024 * 1024, files: 1 } }).single('file'), asyncRoute(student.uploadProfileFile));
router.post('/profile', asyncRoute(student.saveProfile));
router.post('/connect-google', googleStart);
router.get('/courses', asyncRoute(student.catalog));
router.post('/courses/:id/save', asyncRoute(student.saveCourse));
router.post('/courses/:id/unsave', asyncRoute(student.unsaveCourse));
router.post('/courses/:id/modules/:moduleId/save', asyncRoute(student.saveModule));
router.post('/courses/:id/modules/:moduleId/unsave', asyncRoute(student.unsaveModule));
router.get('/courses/:id', asyncRoute(student.courseDetail));
router.post('/courses/:id/enroll', asyncRoute(student.enroll));
router.get('/learning', asyncRoute(student.myLearning));
router.use('/learn/:id', asyncRoute(student.requireCompleteProfile));
router.get('/learn/:id', asyncRoute(student.learn));
router.get('/learn/:id/materials/:moduleId/:sourceId/:key', asyncRoute(student.moduleMaterial));
router.post('/learn/:id/materials/:moduleId/confirm', asyncRoute(student.confirmModuleReading));
router.post('/learn/:id/complete', asyncRoute(student.completeLesson));
router.post('/learn/:id/heartbeat', asyncRoute(student.heartbeat));
const assessmentLimit = rateLimit({ windowMs: 60000, limit: 15, message: 'Too many submissions. Please wait a minute and try again.' });
router.get('/learn/:id/result/:nonce', asyncRoute(student.quizResult));
router.get('/learn/:id/quiz/:moduleId', asyncRoute(student.quizPage));
router.post('/learn/:id/quiz/:moduleId', assessmentLimit, asyncRoute(student.submitQuiz));
router.post('/learn/:id/draft/:scope', asyncRoute(student.saveDraft));
router.post('/learn/:id/retake/:moduleId', asyncRoute(student.retakeModule));
router.post('/learn/:id/restart/:scope', asyncRoute(student.restartQuiz));
router.get('/learn/:id/activities', asyncRoute(student.activities));
router.post('/learn/:id/activities/:taskId', asyncRoute(student.submitTask));
router.post('/learn/:id/feedback', asyncRoute(student.submitFeedback));
router.get('/learn/:id/final', asyncRoute(student.quizPage));
router.post('/learn/:id/final', assessmentLimit, asyncRoute(student.submitQuiz));
router.get('/assessment', asyncRoute(student.assessmentPage));
router.post('/assessment/draft', asyncRoute(student.saveDiagnosticDraft));
router.get('/learn/:id/review/:scope', asyncRoute(student.reviewAnswers));
router.post('/assessment', assessmentLimit, asyncRoute(student.submitAssessment));
router.get('/results', asyncRoute(student.results));
router.get('/results/download', asyncRoute(student.downloadReport));
router.get('/careers', asyncRoute(student.careers));
router.post('/careers/generate', rateLimit({ windowMs: 3600000, limit: 5, keyGenerator: req => String(req.user.id), message: 'AI guidance is limited to 5 requests per hour.' }), asyncRoute(student.generateGuidance));
router.get('/notifications', asyncRoute(student.notifications));
router.post('/notifications/read', asyncRoute(student.readNotifications));
router.get('/achievements', asyncRoute(student.achievements));
router.get('/credentials/:id/certificate', asyncRoute(student.certificate));
router.get('/credentials/:id/badge', asyncRoute(student.badge));
export default router;
