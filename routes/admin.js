import * as extra from '../controllers/adminExtensions.js';
import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import { requireUser, requireAdmin, asyncRoute } from '../middleware/security.js';
import { googleStart } from '../controllers/googleController.js';
import * as c from '../controllers/adminController.js';
const r = Router(); r.use(requireUser, requireAdmin);
r.get('/', asyncRoute(c.dashboard));
r.get('/faculty', asyncRoute(c.facultyManagement)); r.get('/credential-approvals', asyncRoute(c.credentialApprovals)); r.post('/credential-approvals/:id', asyncRoute(c.reviewCredential));
r.get('/users', asyncRoute(c.users)); r.post('/users', asyncRoute(c.createUser));
r.get('/users/:id', asyncRoute(c.userDetail)); r.post('/users/:id', asyncRoute(c.saveUser));
r.post('/users/:id/approval', asyncRoute(c.approveFaculty));
r.post('/faculty/:id/status', asyncRoute(c.setFacultyActive));
r.post('/users/:id/password', rateLimit({ windowMs: 60000, limit: 10 }), asyncRoute(c.resetPassword));
r.get('/sections', asyncRoute(c.sections)); r.post('/sections', asyncRoute(c.saveSection)); r.post('/sections/:id', asyncRoute(c.saveSection)); r.post('/sections/:id/delete', asyncRoute(c.deleteSection));
r.get('/courses', asyncRoute(c.courses)); r.post('/courses/:id', asyncRoute(c.saveCourse)); r.post('/courses/:id/approve-publication', asyncRoute(c.approvePublication));
r.post('/courses/:id/republish', asyncRoute(c.republishCourse));
r.post('/courses/:id/decline-publication', asyncRoute(c.declinePublication));
r.get('/credentials', asyncRoute(c.credentials)); r.post('/credentials/:id/revoke', asyncRoute(c.revokeCredential));
r.get('/announcements', asyncRoute(c.announcements)); r.post('/announcements', asyncRoute(c.saveAnnouncement)); r.post('/announcements/:id', asyncRoute(c.saveAnnouncement));
r.get('/careers', asyncRoute(c.careerPaths)); r.post('/careers', asyncRoute(c.saveCareer)); r.post('/careers/:id', asyncRoute(c.saveCareer));
r.post('/settings/course-ai', asyncRoute(c.saveCourseAiSettings));
r.get('/settings', asyncRoute(c.settings)); r.post('/settings', asyncRoute(c.saveSettings));
r.get('/audit', asyncRoute(c.auditLogs)); r.get('/reports', asyncRoute(c.reports)); r.get('/reports/export', asyncRoute(c.exportReport));
r.get('/account', c.account); r.get('/profile', (req, res) => res.redirect('/admin/account'));
r.post('/account/password', rateLimit({ windowMs: 60000, limit: 5 }), asyncRoute(c.changePassword));
r.post('/connect-google', googleStart);
r.get('/academic', asyncRoute(extra.academic)); r.post('/academic/:id', asyncRoute(extra.correct));
r.post('/courses/:id/ownership', asyncRoute(extra.ownership)); r.get('/courses/:id/history', asyncRoute(extra.history));
r.get('/ai', asyncRoute(extra.ai));
r.get('/competencies', asyncRoute(extra.competencies)); r.post('/competencies', asyncRoute(extra.saveCompetencies));
r.get('/maintenance', asyncRoute(extra.maintenance));
export default r;
